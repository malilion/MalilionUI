// Generate per-component style entry points for on-demand loading.
//   node scripts/build-style-map.mjs          write src/styles/on-demand/*.js + map.json
//   node scripts/build-style-map.mjs --check  exit 1 if they're out of date
//
// For each component it finds every `ml-*` block the component (and the
// components / helpers it imports) uses, then every stylesheet that defines
// one of those blocks — plus stylesheets holding @keyframes those rely on.
// The full stylesheet's import order is kept, so the cascade is unchanged.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, relative } from 'node:path'

const root = fileURLToPath(new URL('..', import.meta.url))
const stylesDir = join(root, 'src/styles')
const compDir = join(root, 'src/components')
const outDir = join(stylesDir, 'on-demand')
const check = process.argv.includes('--check')

const CORE = ['fonts.css', 'tokens.css', 'base.css']

// Stylesheets in the order index.css loads them.
const order = [...readFileSync(join(stylesDir, 'index.css'), 'utf8').matchAll(/@import '\.\/(.+?)';/g)].map((m) => m[1])
const sheets = order.filter((f) => !CORE.includes(f))

const blockOf = (cls) => cls.split(/__|--/)[0].replace(/-+$/, '')

// What each stylesheet defines and needs.
const sheetInfo = new Map()
for (const file of sheets) {
  const css = readFileSync(join(stylesDir, file), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')
  // Each selector's set of ml-* blocks. A rule only matters when every block
  // it mentions is on the page: `.ml-transfer .ml-btn` needs a transfer too.
  const selectorText = css.replace(/\{[^{}]*\}/g, '\n')
  const rules = []
  for (const sel of selectorText.split(/[,\n]/)) {
    const set = new Set([...sel.matchAll(/\.(ml-[a-z0-9_-]+)/g)].map((m) => blockOf(m[1])))
    if (set.size) rules.push(set)
  }
  const keyframes = new Set([...css.matchAll(/@keyframes\s+([\w-]+)/g)].map((m) => m[1]))
  const animations = new Set(
    [...css.matchAll(/animation(?:-name)?\s*:\s*([^;]+)/g)].flatMap((m) => [...m[1].matchAll(/\b(ml-[\w-]+)/g)].map((x) => x[1])),
  )
  sheetInfo.set(file, { rules, keyframes, animations })
}
const coreKeyframes = new Set(
  CORE.flatMap((f) => [...readFileSync(join(stylesDir, f), 'utf8').matchAll(/@keyframes\s+([\w-]+)/g)].map((m) => m[1])),
)

/** A stylesheet plus every stylesheet holding keyframes it animates with. */
function withKeyframeDeps(files) {
  const out = new Set(files)
  let grew = true
  while (grew) {
    grew = false
    for (const f of [...out]) {
      for (const anim of sheetInfo.get(f).animations) {
        if (coreKeyframes.has(anim) || sheetInfo.get(f).keyframes.has(anim)) continue
        const owner = sheets.find((s) => sheetInfo.get(s).keyframes.has(anim))
        if (owner && !out.has(owner)) {
          out.add(owner)
          grew = true
        }
      }
    }
  }
  return out
}

// Blocks used by a source file and everything it imports locally.
const blockCache = new Map()
function blocksOf(path, seen = new Set()) {
  if (seen.has(path)) return new Set()
  seen.add(path)
  const src = readFileSync(path, 'utf8')
  const blocks = new Set([...src.matchAll(/\bml-[a-z0-9_-]+/g)].map((m) => blockOf(m[0])).filter((b) => b.length > 3))
  for (const m of src.matchAll(/from '(\.{1,2}\/[^']+)'/g)) {
    let dep = join(dirname(path), m[1])
    if (!/\.(vue|ts)$/.test(dep)) dep += existsSync(`${dep}.ts`) ? '.ts' : '.vue'
    if (!existsSync(dep) || !dep.startsWith(join(root, 'src'))) continue
    if (dep.includes('/styles/')) continue
    for (const b of blocksOf(dep, seen)) blocks.add(b)
  }
  return blocks
}

function sheetsFor(path) {
  const used = blocksOf(path)
  const files = sheets.filter((f) => sheetInfo.get(f).rules.some((set) => [...set].every((b) => used.has(b))))
  const all = withKeyframeDeps(files)
  return sheets.filter((f) => all.has(f))
}

// Public components = the ones index.ts registers.
const index = readFileSync(join(root, 'src/index.ts'), 'utf8')
const components = [...index.matchAll(/^import (Ml\w+) from '\.\/components\/(Ml\w+)\.vue'/gm)].map((m) => m[1])
const directives = { 'v-paw-stamp': join(root, 'src/pawStamp.ts'), 'v-loading': join(root, 'src/loading.ts') }

// Each entry is a tiny JS module of CSS imports rather than a CSS file of
// @imports: bundlers load every stylesheet module once, at its first import,
// so two components sharing field.css can't re-apply it after a later
// stylesheet that refines it (CSS @import would duplicate it).
const map = {}
const files = {}
const entry = (name, list) =>
  `// Generated by scripts/build-style-map.mjs — styles for ${name}.\n` +
  `import '../core.css'\n` +
  list.map((f) => `import '../${f}'\n`).join('')
for (const name of components) {
  const list = sheetsFor(join(compDir, `${name}.vue`))
  map[name] = list
  files[`${name}.js`] = entry(name, list)
}
for (const [name, path] of Object.entries(directives)) {
  const list = sheetsFor(path)
  map[name] = list
  files[`${name}.js`] = entry(name, list)
}
files['map.json'] = JSON.stringify(map, null, 2) + '\n'

const core = `/* Generated by scripts/build-style-map.mjs — fonts, tokens and base styles every component needs. */\n${CORE.map((f) => `@import './${f}';\n`).join('')}`

if (check) {
  const stale = Object.entries(files).filter(([f, text]) => {
    const p = join(outDir, f)
    return !existsSync(p) || readFileSync(p, 'utf8') !== text
  })
  const coreStale = !existsSync(join(stylesDir, 'core.css')) || readFileSync(join(stylesDir, 'core.css'), 'utf8') !== core
  if (stale.length || coreStale) {
    console.error(`On-demand styles are out of date (${stale.map(([f]) => f).join(', ')}). Run: node scripts/build-style-map.mjs`)
    process.exit(1)
  }
  console.log('on-demand styles up to date')
} else {
  rmSync(outDir, { recursive: true, force: true })
  mkdirSync(outDir, { recursive: true })
  for (const [f, text] of Object.entries(files)) writeFileSync(join(outDir, f), text)
  writeFileSync(join(stylesDir, 'core.css'), core)
  console.log(`${relative(root, outDir)}: ${components.length} components, ${Object.keys(directives).length} directives`)
}
