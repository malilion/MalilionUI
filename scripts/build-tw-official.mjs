// Regenerate src/tw-official-calendar.ts — the official 政府行政機關辦公日曆表 that
// MlLunarCalendar / LunarCalendar apply with `official`.
//   node scripts/build-tw-official.mjs
//
// Source: 行政院人事行政總處「中華民國政府行政機關辦公日曆表」, 政府資料開放平臺
// https://data.gov.tw/dataset/14718 (政府資料開放授權條款－第1版). Each row is
// 西元日期, 星期, 是否放假 (2 = day off, 0 = working day), 備註.
//
// Only days that differ from "weekends off, weekdays on", or that carry a name,
// are kept: holidays, 補假, 調整放假, 補行上班.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const BASE = 'https://www.dgpa.gov.tw/FileConversion?filename=dgpa/files/'
const SOURCES = {
  2024: '202407/777152e9-fdd1-4a61-876c-2733e7692538.csv',
  // 114 年, the 2025-10-20 update (adds the days of the 2025 紀念日及節日實施條例).
  2025: '202510/b84cb88a-803c-4621-a843-d637b2775615.csv',
  2026: '202506/a52331bd-a189-466b-b0f0-cae3062bbf74.csv',
  2027: '202607/f538b1ff-ba60-4c63-9477-10db8e6612d1.csv',
}
const target = fileURLToPath(new URL('../src/tw-official-calendar.ts', import.meta.url))

const years = {}
for (const [year, file] of Object.entries(SOURCES)) {
  // Most years are UTF-8 (with a BOM); some are Big5.
  const bytes = new Uint8Array(await (await fetch(`${BASE}${file}`)).arrayBuffer())
  let text
  try {
    text = new TextDecoder('utf-8', { fatal: true }).decode(bytes)
  } catch {
    text = new TextDecoder('big5').decode(bytes)
  }
  text = text.replace(/^\uFEFF/, '')
  const rows = text.trim().split(/\r?\n/).slice(1)
  const days = []
  for (const row of rows) {
    const [date, weekday, off, note = ''] = row.split(',').map((c) => c.trim())
    if (!/^\d{8}$/.test(date)) continue
    const weekend = weekday === '六' || weekday === '日'
    const isOff = off === '2'
    if (isOff === weekend && !note) continue
    days.push(`${date.slice(4)}${isOff ? '+' : '-'}${note}`)
  }
  if (!days.length) throw new Error(`no rows for ${year}`)
  years[year] = days
}

const out = `// Generated by scripts/build-tw-official.mjs — do not edit.
// 行政院人事行政總處「中華民國政府行政機關辦公日曆表」(https://data.gov.tw/dataset/14718,
// 政府資料開放授權條款－第1版): only days that differ from "weekends off", or carry a name.
// Each entry is MMDD, then + (day off) or - (working day), then the 備註.

export const TW_OFFICIAL_CALENDAR: Readonly<Record<number, readonly string[]>> = {
${Object.entries(years)
  .map(([y, days]) => `  ${y}: [\n${days.map((d) => `    '${d}',`).join('\n')}\n  ],`)
  .join('\n')}
}
`
writeFileSync(target, out)
